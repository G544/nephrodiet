from app.domain import ckd_guidelines
from app.domain.schemas import (
    CalorieTargetInput,
    DaySkeleton,
    ProfileInput,
)

_ACTIVITY_RU = {
    "sedentary": "малоподвижный",
    "light": "лёгкая активность",
    "moderate": "умеренная активность",
    "active": "высокая активность",
}
_GOAL_RU = {
    "maintenance": "удержание веса",
    "weight_gain": "набор веса",
}
_SEX_RU = {"male": "мужской", "female": "женский"}

_MEALS_PER_DAY = 3
# Leave headroom under the per-meal average so three meals don't creep over the daily cap.
_PER_MEAL_BUDGET_RATIO = 0.9


def _per_meal_budget(daily_limit_g: float) -> float:
    return daily_limit_g / _MEALS_PER_DAY * _PER_MEAL_BUDGET_RATIO


def _ckd_stage4_block() -> str:
    return f"""Пациент на ХБП (хронической болезни почек) 4 стадии, додиализной. Врач не давал точных \
цифр по калию и фосфору, поэтому используются общие ориентиры для 4 стадии ХБП (их нужно соблюдать так \
же строго, как ограничения по соли и белку выше):
- калий: не более {ckd_guidelines.POTASSIUM_LIMIT_MG_PER_DAY:.0f} мг/день на ВЕСЬ ДЕНЬ
- фосфор: не более {ckd_guidelines.PHOSPHORUS_LIMIT_MG_PER_DAY:.0f} мг/день на ВЕСЬ ДЕНЬ

Избегай или используй в минимальном количестве продукты с высоким содержанием калия: \
{ckd_guidelines.HIGH_POTASSIUM_INGREDIENTS_RU}.
Избегай или используй в минимальном количестве продукты с высоким содержанием фосфора: \
{ckd_guidelines.HIGH_PHOSPHORUS_INGREDIENTS_RU}.
Также избегай: {ckd_guidelines.CAUTION_INGREDIENTS_RU} — умеренно высокое содержание и калия, и фосфора.

{ckd_guidelines.POTATO_PREP_INSTRUCTION_RU}
Если картофель используется в рецепте — обязательно включи вымачивание в пошаговую инструкцию \
приготовления, а не просто упомяни его вскользь."""


def _profile_block(profile: ProfileInput, calorie_target: CalorieTargetInput) -> str:
    salt_per_meal = _per_meal_budget(profile.salt_limit_g)
    protein_per_meal = _per_meal_budget(profile.protein_limit_g)
    return f"""Параметры пациента:
- возраст: {profile.age} лет
- вес: {profile.weight_kg} кг, рост: {profile.height_cm} см, пол: {_SEX_RU[profile.sex]}
- уровень активности: {_ACTIVITY_RU[profile.activity_level]}
- СКФ (контекст, не для прямого расчёта): {profile.egfr}
- цель: {_GOAL_RU[profile.goal]}

Жёсткие ограничения от врача на ВЕСЬ ДЕНЬ (не превышать):
- соль: не более {profile.salt_limit_g} г/день
- белок: не более {profile.protein_limit_g} г/день

В день 3 приёма пищи (завтрак/обед/ужин), поэтому ориентировочный бюджет НА ОДИН ПРИЁМ ПИЩИ (на одну \
порцию, то есть на то, что реально съедает пациент за один приём пищи):
- белок: не более {protein_per_meal:.0f} г
- соль: не более {salt_per_meal:.1f} г
Это довольно мало по сравнению с обычным "здоровым" рационом — типичная порция мяса/рыбы/птицы весом \
150-200 г уже содержит 30-45 г белка, то есть ПРЕВЫШАЕТ бюджет одного приёма пищи. Используй порции мяса, \
рыбы, птицы, яиц, творога и других белковых продуктов весом примерно 50-80 г на приём пищи, а не 150-200 г.

Целевая калорийность дня: {calorie_target.target_kcal:.0f} ккал (минимум {calorie_target.min_kcal:.0f} ккал — \
дефицит калорий НЕДОПУСТИМ, профицит до {calorie_target.max_kcal:.0f} ккал — это нормально).

КРИТИЧЕСКИ ВАЖНО: белок строго ограничен, а калорийность должна быть высокой (профицит/норма). Это значит, \
что недостающие калории нужно добирать НЕ увеличением порций белковых продуктов, а за счёт продуктов с \
высокой калорийностью и низким содержанием белка, калия и фосфора: растительные и сливочные масла, белые \
крупы и макароны, белый хлеб, сахар/мёд. Картофель тоже подходит, но ТОЛЬКО с вымачиванием (см. ниже). \
НЕ используй для набора калорийности орехи, семечки и авокадо — они высококалорийны, но перегружены калием \
и фосфором. Никогда не наращивай калорийность за счёт мяса/рыбы/птицы/яиц/творога/бобовых сверх указанного \
белкового бюджета.

{_ckd_stage4_block()}"""


def build_skeleton_prompt(
    profile: ProfileInput,
    preferences: list[str],
    calorie_target: CalorieTargetInput,
) -> str:
    prefs_block = (
        "\n".join(f"- {p}" for p in preferences) if preferences else "(пожеланий нет)"
    )

    return f"""Ты — диетолог, составляющий недельное меню почечной (нефро-) диеты для пациента.

{_profile_block(profile, calorie_target)}

Пожелания пациента (учитывай частоту буквально, интерпретируй сам):
{prefs_block}

Составь меню на 7 дней (day_index от 0 до 6), для каждого дня — завтрак, обед, ужин. Каждое блюдо — новая \
идея, придуманная тобой сейчас (recipe_name и short_description).
Требования:
1. Разнообразие: не повторяй одно и то же блюдо в течение недели без необходимости, чередуй виды белка \
(курица/говядина/рыба/вегетарианское) и типы блюд.
2. Строго соблюдай частотные пожелания пациента (например "суп раз в неделю" — суп не чаще одного раза \
за 7 дней; "говядина хотя бы раз в неделю" — минимум один приём пищи с говядиной).
3. Каждая идея блюда должна укладываться в белковый бюджет ОДНОГО приёма пищи, указанный выше (используй \
небольшие порции белковых продуктов и дополняй калорийность гарнирами/маслами/крупами, а не размером \
порции мяса/рыбы), и не полагаться на продукты из списков высокого калия/фосфора выше. Соль, калорийность, \
калий и фосфор точно рассчитаются на следующем этапе."""


def build_new_recipe_prompt(
    day: DaySkeleton,
    slot_name: str,
    profile: ProfileInput,
    calorie_target: CalorieTargetInput,
) -> str:
    slot = getattr(day, slot_name)
    protein_per_meal = _per_meal_budget(profile.protein_limit_g)
    salt_per_meal = _per_meal_budget(profile.salt_limit_g)
    potassium_per_meal = ckd_guidelines.POTASSIUM_LIMIT_MG_PER_DAY / _MEALS_PER_DAY * _PER_MEAL_BUDGET_RATIO
    phosphorus_per_meal = ckd_guidelines.PHOSPHORUS_LIMIT_MG_PER_DAY / _MEALS_PER_DAY * _PER_MEAL_BUDGET_RATIO
    kcal_per_meal_target = calorie_target.target_kcal / _MEALS_PER_DAY
    kcal_per_meal_max = calorie_target.max_kcal / _MEALS_PER_DAY
    return f"""Ты — диетолог, детализирующий один рецепт для почечной (нефро-) диеты.

{_profile_block(profile, calorie_target)}

Нужно детализировать блюдо на приём пищи "{slot.meal_slot}" ({day.weekday_name_ru}):
- название: {slot.recipe_name}
- краткое описание: {slot.short_description}
- тип блюда: {slot.dish_type}
- тип белка: {slot.protein_type}

Составь полный рецепт РОВНО на {2} порции (это блюдо готовится сразу на семью из 2 человек, но лимиты \
ниже — это лимиты пациента на ОДНУ порцию, то есть на то, что съедает именно он):
- список ингредиентов с граммовками (amount_g) под 2 порции
- пошаговая инструкция приготовления (включая вымачивание картофеля, если он используется)

ВАЖНО про пищевую ценность: НЕ считай калории/белок/соль/жиры/углеводы/калий/фосфор для блюда целиком \
одним числом «на глаз». Вместо этого для КАЖДОГО ингредиента в списке укажи его СОБСТВЕННУЮ пищевую \
ценность (калории, белок, соль, жиры, углеводы, калий, фосфор) именно для того количества (amount_g), \
которое ты использовал в рецепте — итоговая пищевая ценность блюда будет посчитана программой как сумма \
по всем ингредиентам, поэтому пропущенный или обнулённый ингредиент напрямую занизит результат. Особенно \
не забывай про белок и калории гарнира (макароны, рис, гречка, картофель, хлеб) — это частая ошибка: \
считают белок только от мяса/рыбы и забывают, что гарнир тоже содержит белок и калории.

Ориентиры на 100 г продукта (белок г / калории ккал / калий мг / фосфор мг), используй как отправную точку \
и скорректируй под фактический вес ингредиента (amount_g):
- курица/индейка (филе): 23 / 165 / 220 / 200
- говядина/свинина (нежирная): 22 / 200 / 320 / 180
- рыба (треска/минтай/хек): 18 / 90 / 350 / 200
- яйцо (1 шт ≈ 50 г): 13 / 155 / 130 / 200
- творог 5%: 17 / 120 / 110 / 160
- макароны, сухие: 12 / 350 / 180 / 150
- рис, сухой: 7 / 350 / 100 / 110
- гречка, сухая: 13 / 340 / 380 / 300
- картофель (после вымачивания): 2 / 77 / 300 (снижено вымачиванием) / 40
- белый хлеб: 8 / 265 / 100 / 90
- растительное/сливочное масло: 0 / 900 / 0 / 0
- овощи (кабачок, огурец, перец, капуста): 1 / 20-30 / 150-250 / 25-40
Для каждого ингредиента переведи эти цифры на его реальный вес (например, 150 г сухих макарон = 1.5× от \
цифр на 100 г).

ЖЁСТКИЕ ТРЕБОВАНИЯ на блюдо ЦЕЛИКОМ (обе порции суммарно, то есть сумма по всем ингредиентам — это ровно \
вдвое больше, чем бюджет одной порции пациента, указанный в параметрах выше):
- калорийность: около {kcal_per_meal_target * 2:.0f} ккал, НЕ БОЛЕЕ {kcal_per_meal_max * 2:.0f} ккал (это \
один из трёх приёмов пищи за день на семью из 2 человек, не весь дневной рацион одного человека).
- белок: не более {protein_per_meal * 2:.0f} г НА ВСЁ БЛЮДО (то есть не более {protein_per_meal:.0f} г белка \
на одну порцию). Ориентиры по белку (на порцию, чтобы не промахнуться): 100 г курицы/индейки/говядины/рыбы \
≈ 20-25 г белка, 1 яйцо ≈ 6 г белка, 100 г творога ≈ 16-18 г белка, 100 г вареной гречки/риса/макарон ≈ \
3-4 г белка, овощи и большинство круп в среднем содержат мало белка. После того как посчитаешь белок всех \
ингредиентов, ЕЩЁ РАЗ сложи их и проверь, что сумма не превышает {protein_per_meal:.0f} г на порцию — если \
превышает, уменьши количество белкового продукта (мясо/рыба/птица/яйца/творог) и пересчитай заново.
- соль: не более {salt_per_meal * 2:.1f} г.
- калий: не более {potassium_per_meal * 2:.0f} мг (не более {potassium_per_meal:.0f} мг на порцию).
- фосфор: не более {phosphorus_per_meal * 2:.0f} мг (не более {phosphorus_per_meal:.0f} мг на порцию).

Про соль: НЕ добавляй соль, соевый соус, бульонные кубики, готовые приправы-смеси, солёные/копчёные \
продукты, твёрдый сыр, консервы, колбасы — это основные источники избытка соли. Используй только свежие \
или замороженные (не консервированные) продукты, лимонный сок, свежие/сушёные травы и специи без соли для \
вкуса. Блюдо без добавленной соли из свежих продуктов обычно содержит менее 0.3-0.5 г соли на порцию за \
счёт натуральной соли в самих продуктах — ориентируйся на это при указании итоговой соли блюда.

Про калий и фосфор: избегай ингредиентов из списков высокого калия/фосфора, указанных выше в параметрах \
пациента. Если используешь картофель или другой крахмалистый корнеплод — вымачивание ОБЯЗАТЕЛЬНО должно \
быть явным шагом в инструкции приготовления, а не подразумеваться.

Если для соблюдения белкового лимита нужно уменьшить порцию мяса/рыбы/птицы/яиц/творога до 50-80 г на \
порцию — уменьши её, а недостающие до целевой калорийности калории добери гарниром, крупой, маслом (но не \
выходя за указанный калорийный лимит блюда и не используя орехи/семечки/авокадо). Пересчитай граммовки \
ингредиентов так, чтобы итоговые калории, белок, соль, калий и фосфор блюда укладывались в эти лимиты — \
это важнее, чем точное соответствие исходному краткому описанию блюда."""


def build_week_review_prompt(
    profile: ProfileInput,
    day_summaries: list[str],
) -> str:
    days_block = "\n".join(day_summaries)
    return f"""Ты — диетолог, проверяющий готовое недельное меню почечной диеты после того, как порции \
блюд могли быть увеличены для достижения нормы калорийности (дефицит калорий был недопустим, поэтому \
порции блюд могли быть увеличены, что могло непреднамеренно увеличить потребление соли, белка, калия и \
фосфора).

Ограничения врача (на одну порцию пациента в день):
- соль: не более {profile.salt_limit_g} г/день
- белок: не более {profile.protein_limit_g} г/день

Общие ориентиры для ХБП 4 стадии (не от врача лично, стандартные значения для этой стадии):
- калий: не более {ckd_guidelines.POTASSIUM_LIMIT_MG_PER_DAY:.0f} мг/день
- фосфор: не более {ckd_guidelines.PHOSPHORUS_LIMIT_MG_PER_DAY:.0f} мг/день

Итоги по дням недели (уже в пересчёте на одну порцию пациента):
{days_block}

Проверь, не стала ли неделя в целом менее полезной для здоровья из-за увеличения порций: не превышены ли \
лимиты соли/белка/калия/фосфора в отдельные дни или в среднем за неделю значительно. Если превышений нет — \
is_within_limits=true, summary_ru — короткое подтверждение, flags — пустой список. Если превышения есть — \
is_within_limits=false, summary_ru — понятное пациенту резюме, что именно и в какие дни много \
(например, "среда и пятница превышают лимит по соли"), flags — по одному элементу на каждую проблему \
(day_index=-1 для проблемы уровня всей недели)."""
